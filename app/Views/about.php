          <p class="text-justify">
            The Directorate of Distance Education was established in the year 2022 with the aim of imparting quality education to the education seekers who are deprived of education due to personal constraints and for those who seek to upgrade their qualification and competence. The Directorate offers open distance learning (ODL) education courses in higher education through distance mode of education to the students of the State of Andhra Pradesh who are deprived of admission into the conventional modes. The Directorate of Distance Education of Yogi Vemana University offers innovative, job-oriented courses well designed for the learners of the distance mode by providing updated reading material and support through the identified distance learning centres.
          </p>
          <p class="text-justify">
            The directorate is located in the Yogi Vemana University campus with a well-equipped Library, Audio-Video, computer Laboratory, well-furnished classrooms, conference halls with latest information and communication technology (ICT) facilities. The students getting admissions in the Open Distance learning mode are offered the same syllabi and class room support through the same experienced faculty of the university as that of the regular students of Yogi Vemana University.
