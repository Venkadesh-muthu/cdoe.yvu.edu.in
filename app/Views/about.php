          <p class="text-justify"><strong>About the Yogi Vemana University</strong></p>
          <p class="text-justify">
            The erstwhile Sri Venkateshwara University Post Graduate Centre in YSR District, Kadapa was upgraded in the year 2006 and Yogi Vemana University was established by an Act of A.P state legislature. Named after the renowned philosopher and thinker and poet Yogi Vemana, the University imbibes the most cherished values of Teaching, research and service in its working and progress. Located on the Kadapa – Pulivendula Highway 15 kilometres from the Kadapa city in a campus of 652 acres the University hosts various courses in majestic well-furnished Sir C.V. Raman Science Block, New Arts Block accompanied with A.P. J Abdul Kalam Central Library and Administrative Buildings. The University offers Post Graduate and Ph.D programmes in provides courses in Arts, Commerce and Science streams.
          </p>
          <p class="text-justify">
            Yogi Vemana University received UGC 2(f) and 12(B) statuses in 2007 and 2011, respectively. In a bid to subject the institute to objective evaluation SSR for NAAC was filed in May 2022 and the University accomplished NAAC ‘A’ grade with 3.13 CGPA in November 2022 in the 2nd Cycle. The University enrolled for the NIRF initiative of MHRD, Government of India and was accorded 92nd rank at National level and 3rd rank at the State level (NIRF-2016). Also ranked in 101-150 band during the year NIRF-2021 and 2022 and between 150-200 band in 2023. The University has at present 101 regular staff, 136 Academic Consultants on its rolls besides 307 non-teaching and 125 outsourcing staff. One of the unfailing strengths of the University is its faculty, relatively young with wide overseas exposure in research endeavours and rich experience in teaching. The faculty has rich research experience in India and abroad besides teaching. Teachers have been encouraged to enrich their pedagogical practices using technology. Presently about 2000+ students are pursuing postgraduate and research programmes. At present as many as 113 affiliated colleges offering undergraduate, postgraduate and professional courses are affiliated to the University, which include P.G., U.G., Law, B.Ed., B.P.Ed. and D.P.Ed.
